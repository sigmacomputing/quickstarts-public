-- Standard-table UNIQUE/PRIMARY KEY metadata is not enforcement. The
-- retrying PO procedure below first UPDATEs this one row inside its transaction,
-- then inspects and writes under the held lock. A conflict/timeout is a
-- failure requiring fresh readback, never an optimistic retry-success.
CREATE TABLE SIGMA_WRITE_DB.SIGMA_MIGRATION8_INV_TEST.INTENT_LOCK (
  LOCK_ID NUMBER(1,0) NOT NULL,
  EPOCH NUMBER(38,0) NOT NULL
);
INSERT INTO SIGMA_WRITE_DB.SIGMA_MIGRATION8_INV_TEST.INTENT_LOCK VALUES (1,0);

CREATE TABLE SIGMA_WRITE_DB.SIGMA_MIGRATION8_INV_TEST.PO_STAGE (
  OPERATION_ID VARCHAR NOT NULL,
  BATCH_FINGERPRINT VARCHAR(64) NOT NULL,
  SOURCE_ROW NUMBER(2,0) NOT NULL,
  SKU VARCHAR NOT NULL,
  QUANTITY NUMBER(38,0) NOT NULL,
  STAGED_AT TIMESTAMP_NTZ(3) NOT NULL
);

-- Typed return fields: operation_id VARCHAR, source_row NUMBER, sku VARCHAR,
-- quantity NUMBER(38,0), status VARCHAR, error_code VARCHAR. VARIANT is the
-- scalar transport; the controller validates every field and queries rows.
-- Current Sigma action VARIANT scalar mapping remains an actual binding gate.
CREATE PROCEDURE SIGMA_WRITE_DB.SIGMA_MIGRATION8_INV_TEST.STAGE_PO(
  P_OPERATION_ID VARCHAR, P_SOURCE_ROW NUMBER(2,0), P_SKU VARCHAR,
  P_QUANTITY NUMBER(38,0), P_BATCH_FINGERPRINT VARCHAR)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_LOCK_COUNT NUMBER(38,0);
  V_PRIOR NUMBER(38,0);
  V_MATCH NUMBER(38,0);
  V_OTHER_BATCH NUMBER(38,0);
BEGIN
  IF (P_OPERATION_ID IS NULL OR P_OPERATION_ID = '' OR
      P_SOURCE_ROW IS NULL OR P_SOURCE_ROW NOT BETWEEN 4 AND 9 OR
      P_SKU IS NULL OR P_SKU = '' OR P_QUANTITY IS NULL OR
      P_BATCH_FINGERPRINT IS NULL OR LENGTH(P_BATCH_FINGERPRINT) <> 64) THEN
    RETURN OBJECT_CONSTRUCT('operation_id', P_OPERATION_ID, 'source_row', P_SOURCE_ROW,
      'sku', P_SKU, 'quantity', P_QUANTITY, 'status', 'FAILURE',
      'error_code', 'INVALID_TYPED_ARGUMENT');
  END IF;
  BEGIN TRANSACTION;
  UPDATE SIGMA_WRITE_DB.SIGMA_MIGRATION8_INV_TEST.INTENT_LOCK
     SET EPOCH = EPOCH + 1 WHERE LOCK_ID = 1;
  SELECT COUNT(*) INTO :V_LOCK_COUNT
    FROM SIGMA_WRITE_DB.SIGMA_MIGRATION8_INV_TEST.INTENT_LOCK WHERE LOCK_ID = 1;
  IF (V_LOCK_COUNT <> 1) THEN
    ROLLBACK;
    RETURN OBJECT_CONSTRUCT('operation_id', P_OPERATION_ID, 'source_row', P_SOURCE_ROW,
      'sku', P_SKU, 'quantity', P_QUANTITY, 'status', 'FAILURE',
      'error_code', 'LOCK_ROW_NOT_EXACTLY_ONE');
  END IF;
  SELECT COUNT(*) INTO :V_OTHER_BATCH
    FROM SIGMA_WRITE_DB.SIGMA_MIGRATION8_INV_TEST.PO_STAGE
   WHERE OPERATION_ID = :P_OPERATION_ID
     AND BATCH_FINGERPRINT <> :P_BATCH_FINGERPRINT;
  -- COUNT_IF returns NULL when no row matches. Normalize to zero so a
  -- changed SKU/quantity cannot make the IF guard UNKNOWN and return RETRY_PRESENT.
  SELECT COUNT(*), COALESCE(COUNT_IF(SKU = :P_SKU AND QUANTITY = :P_QUANTITY
       AND BATCH_FINGERPRINT = :P_BATCH_FINGERPRINT), 0)
    INTO :V_PRIOR, :V_MATCH
    FROM SIGMA_WRITE_DB.SIGMA_MIGRATION8_INV_TEST.PO_STAGE
   WHERE OPERATION_ID = :P_OPERATION_ID AND SOURCE_ROW = :P_SOURCE_ROW;
  IF (V_OTHER_BATCH > 0 OR V_PRIOR > 1 OR (V_PRIOR = 1 AND V_MATCH <> 1)) THEN
    ROLLBACK;
    RETURN OBJECT_CONSTRUCT('operation_id', P_OPERATION_ID, 'source_row', P_SOURCE_ROW,
      'sku', P_SKU, 'quantity', P_QUANTITY, 'status', 'FAILURE',
      'error_code', 'OPERATION_RETRY_INPUT_MISMATCH');
  END IF;
  IF (V_PRIOR = 1) THEN
    COMMIT;
    RETURN OBJECT_CONSTRUCT('operation_id', P_OPERATION_ID, 'source_row', P_SOURCE_ROW,
      'sku', P_SKU, 'quantity', P_QUANTITY, 'status', 'RETRY_PRESENT',
      'error_code', '');
  END IF;
  INSERT INTO SIGMA_WRITE_DB.SIGMA_MIGRATION8_INV_TEST.PO_STAGE
    (OPERATION_ID, BATCH_FINGERPRINT, SOURCE_ROW, SKU, QUANTITY, STAGED_AT)
    VALUES (:P_OPERATION_ID, :P_BATCH_FINGERPRINT, :P_SOURCE_ROW,
      :P_SKU, :P_QUANTITY, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ(3));
  COMMIT;
  RETURN OBJECT_CONSTRUCT('operation_id', P_OPERATION_ID, 'source_row', P_SOURCE_ROW,
    'sku', P_SKU, 'quantity', P_QUANTITY, 'status', 'STAGED', 'error_code', '');
EXCEPTION WHEN OTHER THEN
  ROLLBACK;
  RAISE;
END;
$$;
